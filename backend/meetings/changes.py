"""What changed in a decision between two points in its chain.

The diff is computed from stored fields by comparison — no model involved. That
is the whole design constraint: a board asking "what changed since March" needs
an answer that is the same every time it is asked and that can be checked
against the database. A summary regenerated by a model on each request is
neither, however fluent it reads.

A prose summary can be produced *from* the finished diff as a display
convenience (``summarise_changes``), and it is explicitly downstream: the model
receives the computed field list and nothing else, so it can phrase the change
but cannot invent one. If that call fails, the structured diff is still the
answer and the endpoint still works.

Fields compared
---------------
Decision status, title, and rationale; the owner and target date of the action
items hanging off the decision; the severity of associated risks; and any
amount mentioned. Amounts are parsed out of the text rather than stored as a
column — there is no money field on Decision, and inventing one to support a
diff would be the tail wagging the dog. The parse is conservative: it reports
a change only when both sides yield a number, so a failed parse produces no
finding rather than a false one.
"""

from __future__ import annotations

import logging
import re
from dataclasses import asdict, dataclass, field

from sqlalchemy.orm import Session

from ..database import ActionItem, Decision, Meeting, Risk

logger = logging.getLogger(__name__)

# Currency-ish amounts: optional symbol, digits with separators, optional
# scale word. Deliberately narrow — a loose pattern turns every stray number
# in a sentence into a "change".
_AMOUNT = re.compile(
    r"(?:[$£€]\s?)?(\d[\d,\s]*(?:\.\d+)?)\s*(k|m|bn|thousand|million|billion)?\b",
    re.IGNORECASE,
)
_SCALE = {
    "k": 1_000,
    "thousand": 1_000,
    "m": 1_000_000,
    "million": 1_000_000,
    "bn": 1_000_000_000,
    "billion": 1_000_000_000,
}

SUMMARY_MAX_TOKENS = 300


@dataclass
class FieldChange:
    """One field that differs between two points in the chain."""

    field: str
    old_value: str | None
    new_value: str | None
    # The meeting in which the new value first appears.
    changed_in_meeting_id: str | None = None
    changed_in_meeting_title: str | None = None
    # Where the new value came from, so the reader can hear it said.
    evidence_id: str | None = None
    start_ms: int | None = None


@dataclass
class ChangeSet:
    decision_id: str
    since_meeting_id: str
    since_meeting_title: str | None = None
    current_meeting_id: str | None = None
    current_meeting_title: str | None = None
    changes: list[FieldChange] = field(default_factory=list)
    # True when `since` names a meeting that is not in this decision's chain.
    out_of_chain: bool = False

    @property
    def changed(self) -> bool:
        return bool(self.changes)

    def to_dict(self) -> dict:
        return asdict(self)


def parse_amount(text: str | None) -> float | None:
    """The first currency-like amount in ``text``, or None.

    Returns None rather than guessing when nothing parses, so a diff never
    reports a money change it cannot substantiate.
    """
    if not text:
        return None
    for match in _AMOUNT.finditer(text):
        digits = match.group(1).replace(",", "").replace(" ", "").strip()
        if not digits or digits == ".":
            continue
        try:
            value = float(digits)
        except ValueError:
            continue
        scale = (match.group(2) or "").lower()
        return value * _SCALE.get(scale, 1)
    return None


def _owner_of(db: Session, decision: Decision) -> str | None:
    """The assignee named on this decision's action items, if exactly one."""
    owners = {
        item.assignee_id
        for item in db.query(ActionItem).filter_by(meeting_id=decision.meeting_id).all()
        if item.assignee_id
    }
    return next(iter(owners)) if len(owners) == 1 else None


def _target_date_of(db: Session, decision: Decision) -> str | None:
    """A stated deadline from the decision's meeting, as text.

    Dates are held as the words the speaker used ("before Friday"), not as
    resolved datetimes — the extractor deliberately does not resolve them, so
    this compares the same strings a reader would see.
    """
    for item in db.query(ActionItem).filter_by(meeting_id=decision.meeting_id).all():
        if item.due_date:
            return str(item.due_date)
        for line in (item.description or "").splitlines():
            if line.lower().startswith("due as stated:"):
                return line.split(":", 1)[1].strip()
    return None


def _severity_of(db: Session, decision: Decision) -> str | None:
    severities = {
        risk.severity for risk in db.query(Risk).filter_by(meeting_id=decision.meeting_id).all() if risk.severity
    }
    return next(iter(severities)) if len(severities) == 1 else None


def _snapshot(db: Session, decision: Decision) -> dict[str, str | None]:
    """The comparable state of a decision at its point in the chain."""
    amount_source = " ".join(filter(None, [decision.title, decision.description, decision.rationale]))
    amount = parse_amount(amount_source)
    return {
        "status": decision.status,
        "title": decision.title,
        "rationale": decision.rationale,
        "owner": _owner_of(db, decision),
        "target_date": _target_date_of(db, decision),
        "risk_severity": _severity_of(db, decision),
        "amount": f"{amount:g}" if amount is not None else None,
    }


def diff_since(db: Session, decision_id: str, since_meeting_id: str) -> ChangeSet:
    """Field-level changes between the ``since`` meeting and the chain's head.

    ``since`` names a *meeting*, not a decision, because that is how the
    question is asked: "what changed since the March board".
    """
    from .timeline import _chain

    decision = db.query(Decision).filter_by(id=decision_id).first()
    if decision is None:
        raise ValueError(f"Decision {decision_id} not found")

    chain = _chain(db, decision)
    titles = {
        row[0]: row[1]
        for row in db.query(Meeting.id, Meeting.title)
        .filter(Meeting.id.in_([item.meeting_id for item in chain if item.meeting_id]))
        .all()
    }

    result = ChangeSet(
        decision_id=decision_id,
        since_meeting_id=since_meeting_id,
        since_meeting_title=titles.get(since_meeting_id),
        current_meeting_id=chain[-1].meeting_id,
        current_meeting_title=titles.get(chain[-1].meeting_id),
    )

    positions = [i for i, item in enumerate(chain) if item.meeting_id == since_meeting_id]
    if not positions:
        # Saying so beats diffing against an arbitrary point and returning
        # changes that answer a question nobody asked.
        result.out_of_chain = True
        return result

    start = positions[0]
    if start >= len(chain) - 1:
        return result  # `since` is already the newest point; nothing after it

    before = _snapshot(db, chain[start])
    for later in chain[start + 1 :]:
        after = _snapshot(db, later)
        for key, new_value in after.items():
            old_value = before.get(key)
            if old_value == new_value:
                continue
            result.changes.append(
                FieldChange(
                    field=key,
                    old_value=old_value,
                    new_value=new_value,
                    changed_in_meeting_id=later.meeting_id,
                    changed_in_meeting_title=titles.get(later.meeting_id),
                    evidence_id=later.evidence_id,
                    start_ms=later.evidence.start_ms if later.evidence else None,
                )
            )
        # Compare each step against the one before it, so a field that changed
        # twice reports both hops rather than collapsing to first-vs-last.
        before = after

    return result


_SUMMARY_SYSTEM_PROMPT = """You turn a computed list of field changes into one short paragraph.

You are given the changes as data. They were computed from a database by
comparison, not by you. Your only job is to phrase them.

Rules:
- State only the changes given. Do not add, infer, combine, or speculate about
  causes.
- If the list is empty, say nothing changed.
- No preamble, no bullet points, no closing remark. Two or three sentences."""


async def summarise_changes(changes: ChangeSet, *, provider=None) -> str | None:
    """A prose rendering of an already-computed diff. Display only.

    Returns None if the model cannot be reached — the structured diff is the
    answer, and this is decoration that must never be load-bearing.
    """
    if not changes.changes:
        return None

    lines = [
        f"- {change.field}: {change.old_value!r} -> {change.new_value!r} "
        f"(in {change.changed_in_meeting_title or 'a later meeting'})"
        for change in changes.changes
    ]
    prompt = "Changes computed from the database:\n" + "\n".join(lines) + "\n\nWrite the short paragraph."

    try:
        if provider is None:
            from ..ai import get_llm_provider

            provider = get_llm_provider()
        completion = await provider.generate(prompt, system=_SUMMARY_SYSTEM_PROMPT, max_tokens=SUMMARY_MAX_TOKENS)
        return completion.text.strip() or None
    except Exception as exc:
        logger.warning("Change summary unavailable for %s: %s", changes.decision_id, exc)
        return None
